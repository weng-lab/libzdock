# Regenerate the clangd support files from a clean build:
#
#   compile_commands.json  compilation database covering every translation
#                          unit; the test objects compile with extra flags
#                          (the Catch2 include path and the DATADIR
#                          definition), so the build must cover the test
#                          binary as well as the library and the tools
#   .clangd                pins the C++ standard-library include paths of
#                          the compiler the build actually used
#
# The .clangd pin works around a clangd failure to auto-detect GCC's C++
# headers on hosts that carry a newer GCC runtime directory without a C++
# frontend: clangd then looks for /usr/include/c++/<newest>, which does not
# exist. The pin is derived from the compiler recorded in the database, and
# also covers files that have no database entry yet (freshly added sources).
#
# Neither file is committed. The script runs make clean first, discarding
# the current build tree, so run it only when no other work is in progress.
#
# Usage: tools/gen_compile_commands.sh (override parallelism with JOBS=N).

set -eu

cd "$(dirname "$0")/.."

if ! command -v bear >/dev/null 2>&1; then
  echo "gen_compile_commands.sh: bear is required (e.g. apt install bear)" >&2
  exit 1
fi

JOBS=${JOBS:-4}

make clean
bear -- make -j"$JOBS" all test/test

python3 - <<'EOF'
import json
import shutil
import subprocess
import sys

with open("compile_commands.json") as f:
    db = json.load(f)
tests = sum(1 for e in db if "/test/" in e["file"])
print("compile_commands.json: %d entries (%d test TUs)" % (len(db), tests))
if not tests:
    sys.exit("no test entries captured; check the build targets")

cc = db[0]["arguments"][0]
if not shutil.which(cc):
    sys.exit("compiler %r not found" % cc)
probe = subprocess.run([cc, "-v", "-E", "-x", "c++", "/dev/null"],
                       capture_output=True, text=True)
lines = probe.stderr.splitlines()
try:
    start = lines.index("#include <...> search starts here:")
    end = lines.index("End of search list.", start)
except ValueError:
    sys.exit("could not read the include search path from %s" % cc)
cpp_dirs = [line.strip() for line in lines[start + 1:end] if "c++" in line]
if not cpp_dirs:
    sys.exit("no C++ standard-library directories found for %s" % cc)

with open(".clangd", "w") as f:
    f.write("# Generated by tools/gen_compile_commands.sh; local clangd aid.\n")
    f.write("CompileFlags:\n  Add:\n")
    for d in cpp_dirs:
        f.write("    - -isystem\n    - %s\n" % d)
print(".clangd: pinned %s" % ", ".join(cpp_dirs))
EOF

if command -v clangd >/dev/null 2>&1; then
  if clangd --check=src/record/RecordText.cpp 2>&1 |
    grep -Eq "completed, [1-9][0-9]* error"; then
    echo "gen_compile_commands.sh: clangd still reports errors" >&2
    exit 1
  fi
  echo "clangd: header resolution verified"
fi
