    return SplitRecord{};
  case RecordType::SPRSDE:
    return SprsdeRecord{};
  case RecordType::SSBOND:
    return SsbondRecord{};
  case RecordType::SYMOP:
    return SymopRecord{};
  case RecordType::TER:
    return TerRecord{};
  case RecordType::TITLE:
    return TitleRecord{};
  case RecordType::TRNSFM:
    return TrnsfmRecord{};
  case RecordType::TURN:
    return TurnRecord{};
